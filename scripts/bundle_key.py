"""Generate src/benchmark_core/_bundled_key.py from the private key file.

Run before compiling: the generated module is imported by
``dataset_crypto.get_key()``, so the compiler builds the key into the binary
instead of shipping it as a separate file. The key file stays its only source;
the module is a generated copy, git-ignored and never edited by hand.

It refuses to bundle a key that does not decrypt every dataset file next to
it, so a key and .bin files from different versions are caught here rather
than on a participant's machine.

Usage:
    uv run python scripts/bundle_key.py                 # data/private/key, checked against data/private/encrypted/
    uv run python scripts/bundle_key.py --private DIR
    uv run python scripts/bundle_key.py --remove        # delete the generated module again
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from benchmark_core import dataset_crypto

OUTPUT = ROOT / "src" / "benchmark_core" / "_bundled_key.py"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--private",
        type=Path,
        default=ROOT / "data" / "private",
        help="folder with key and encrypted/ (default: data/private)",
    )
    parser.add_argument("--remove", action="store_true", help="delete the generated module")
    args = parser.parse_args()

    if args.remove:
        OUTPUT.unlink(missing_ok=True)
        print(f"removed {OUTPUT}")
        return 0

    key_path = args.private / "key"
    if not key_path.is_file():
        raise SystemExit(f"no key at {key_path}")
    text = key_path.read_text().strip()
    key = dataset_crypto.decode_key(text)

    blobs = sorted((args.private / "encrypted").glob("*.bin"))
    if not blobs:
        raise SystemExit(f"no .bin files in {args.private / 'encrypted'} to check the key against")
    for blob in blobs:
        try:
            dataset_crypto.load_encrypted(blob, blob.stem, key)
        except ValueError as exc:
            raise SystemExit(f"{blob.name}: key does not match ({exc}); nothing bundled") from None

    OUTPUT.write_text(
        f'# Generated by scripts/bundle_key.py from data/private/key. Do not edit or commit.\nKEY = "{text}"\n'
    )
    OUTPUT.chmod(0o600)
    print(f"key checked against {len(blobs)} dataset file(s), written to {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
