"""Put the encrypted datasets and their key into the package, ready to run or compile.

From the private folder (``data/private/`` by default) it:

1. checks that ``key`` decrypts every ``encrypted/*.bin``, so a key and files
   from different versions are caught here rather than on a participant's
   machine; nothing changes if one does not match,
2. copies the ``.bin`` files into ``src/benchmark_core/datasets/data/``, where
   the registry discovers them,
3. writes ``src/benchmark_core/_bundled_key.py``, which ``dataset_crypto.get_key()``
   imports, so a compiler builds the key into the binary instead of shipping
   it as a separate file.

The key file stays the key's only source; everything written here is a
generated, git-ignored copy that is never edited by hand.

Usage:
    uv run python scripts/bundle_data.py
    uv run python scripts/bundle_data.py --private DIR
    uv run python scripts/bundle_data.py --remove     # delete everything this script wrote
"""

import argparse
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from benchmark_core import dataset_crypto  # noqa: E402

KEY_MODULE = ROOT / "src" / "benchmark_core" / "_bundled_key.py"
DATA_DIR = ROOT / "src" / "benchmark_core" / "datasets" / "data"


def remove() -> None:
    KEY_MODULE.unlink(missing_ok=True)
    for blob in DATA_DIR.glob("*.bin"):
        blob.unlink()
    print(f"removed {KEY_MODULE.name} and the dataset files in {DATA_DIR}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--private",
        type=Path,
        default=ROOT / "data" / "private",
        help="folder with key and encrypted/ (default: data/private)",
    )
    parser.add_argument("--remove", action="store_true", help="delete the bundled key and dataset files")
    args = parser.parse_args()

    if args.remove:
        remove()
        return 0

    key_path = args.private / "key"
    if not key_path.is_file():
        raise SystemExit(f"no key at {key_path}")
    text = key_path.read_text().strip()
    key = dataset_crypto.decode_key(text)

    blobs = sorted((args.private / "encrypted").glob("*.bin"))
    if not blobs:
        raise SystemExit(f"no .bin files in {args.private / 'encrypted'}")
    for blob in blobs:
        try:
            dataset_crypto.load_encrypted(blob, blob.stem, key)
        except ValueError as exc:
            raise SystemExit(f"{blob.name}: key does not match ({exc}); nothing bundled") from None

    # Replace rather than add: a dataset dropped from the private folder must
    # not linger in the package.
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    for old in DATA_DIR.glob("*.bin"):
        old.unlink()
    for blob in blobs:
        shutil.copy2(blob, DATA_DIR / blob.name)

    KEY_MODULE.write_text(
        f'# Generated by scripts/bundle_data.py from data/private/key. Do not edit or commit.\nKEY = "{text}"\n'
    )
    KEY_MODULE.chmod(0o600)
    print(f"key checked against {len(blobs)} dataset file(s); copied them to {DATA_DIR} and wrote {KEY_MODULE.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
