#!/usr/bin/env bash
#
# Generates a working local .env and .seed-credentials from scratch.
#
# The point is that no secret ever has to travel. Every value produced here is
# local to one developer's machine and disposable: the database and the broker
# are containers on localhost, the session secret signs cookies nobody else
# will ever hold. Sending these to a colleague would be strictly worse than
# letting them run this script, because a shared secret is a secret with an
# unknown blast radius and these have none.
#
# The two things that genuinely cannot be generated -- PLGrid credentials and
# the OAuth client secrets -- are deliberately left empty. Neither is needed to
# run the control plane locally; see docs/LOCAL_SETUP.md for what that costs.

set -euo pipefail

cd "$(dirname "$0")/.."

FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

if [ -e .env ] && [ "$FORCE" -eq 0 ]; then
    echo "refusing to overwrite an existing .env (pass --force if that is what you want)" >&2
    exit 1
fi

# `openssl rand -base64` is available everywhere docker is; tr trims the
# characters that would need quoting inside a compose interpolation.
secret() { openssl rand -base64 "$1" | tr -d '/+=\n' | cut -c "1-$2"; }

umask 077

cat > .env <<EOF
# Generated by scripts/bootstrap-env.sh -- local development only.
# Every value here is disposable. Regenerate rather than share.

POSTGRES_DB=benchmark_auth
POSTGRES_USER=benchmark_user
POSTGRES_PASSWORD=$(secret 32 24)
POSTGRES_PORT=5432

RABBITMQ_USER=benchmark_user
RABBITMQ_PASSWORD=$(secret 32 24)
RABBITMQ_PORT=5672
RABBITMQ_MANAGEMENT_PORT=15672

API_PORT=8000
FRONTEND_PORT=8501

# Athena (PLGrid). Personal credentials -- never shared, never committed.
# Leave empty: the worker, poller and downloader will not reach the cluster,
# which is expected locally. Everything else runs.
ATHENA_HOST=
ATHENA_USER=
ATHENA_PASSWORD=
ATHENA_ACCOUNT=
ATHENA_REMOTE_PATH=
POLL_EVERY=60

# Signs session cookies. Rotating it logs everyone out; it is not shared with
# any other service and has no value outside this machine.
SESSION_SECRET=$(secret 64 48)

# 8080, not 8000: the task API already claims \${API_PORT:-8000} and the two
# would refuse to bind together on a default \`docker compose up\`.
WEB_PORT=8080
PUBLIC_RESULTS=1
DAILY_SUBMISSION_LIMIT=3
VALIDATOR_ENABLED=0
EOF

cat > .seed-credentials <<EOF
# Generated by scripts/bootstrap-env.sh -- passwords for the seeded demo
# accounts. Read by tools/local_backend/seed.py from the environment.
SEED_ADMIN_PASSWORD=$(secret 32 20)
SEED_USER_PASSWORD=$(secret 32 20)
EOF

chmod 600 .env .seed-credentials

echo "wrote .env and .seed-credentials (mode 600, both gitignored)"
echo
echo "next:"
echo "  docker compose up -d --build postgres rabbitmq web outbox_publisher"
echo "  see docs/LOCAL_SETUP.md for seeding and the walk-through"
